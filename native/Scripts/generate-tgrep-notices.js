#!/usr/bin/env node
'use strict';

// Reproduce notices from the same locked, target-specific Cargo dependency
// graph that builds the universal library. Run after build-tgrep.sh has fetched
// its packages. Offline/locked metadata forbids resolving a moving dependency.
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const root = path.resolve(__dirname, '../..');
const output = path.join(root, 'native/Resources/TgrepThirdPartyNotices.txt');
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(argument => argument !== '--check')) {
  throw new Error('Usage: node native/Scripts/generate-tgrep-notices.js [--check]');
}

const packages = new Map();
const runtime = new Set();
const compare = (left, right) => left < right ? -1 : left > right ? 1 : 0;
const key = value => `${value.name}@${value.version}`;

for (const target of ['aarch64-apple-darwin', 'x86_64-apple-darwin']) {
  const metadata = JSON.parse(execFileSync('cargo', [
    'metadata', '--locked', '--offline', '--format-version', '1',
    '--filter-platform', target,
    '--manifest-path', path.join(root, 'native/TgrepBridge/Cargo.toml'),
  ], { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 }));
  const byID = new Map(metadata.packages.map(value => [value.id, value]));
  const nodes = new Map(metadata.resolve.nodes.map(value => [value.id, value]));

  function visit(id, runtimeOnly, seen = new Set()) {
    if (seen.has(id)) return;
    seen.add(id);
    const value = byID.get(id);
    if (!value) throw new Error(`Cargo omitted package metadata for ${id}`);
    if (runtimeOnly && value.targets.some(item => item.kind.includes('proc-macro'))) return;
    if (value.name !== 'ccbuddy-tgrep') {
      const existing = packages.get(key(value));
      if (existing && existing.source !== value.source) {
        throw new Error(`Ambiguous notice source for ${key(value)}`);
      }
      packages.set(key(value), value);
      if (runtimeOnly) runtime.add(key(value));
    }
    for (const dependency of nodes.get(id)?.deps ?? []) {
      if (dependency.dep_kinds.some(kind => kind.kind === null || (!runtimeOnly && kind.kind === 'build'))) {
        visit(dependency.pkg, runtimeOnly, seen);
      }
    }
  }
  visit(metadata.resolve.root, false);
  visit(metadata.resolve.root, true);
}

function licenseFiles(value) {
  const directory = path.dirname(value.manifest_path);
  const files = fs.readdirSync(directory, { withFileTypes: true })
    .filter(entry => entry.isFile() && /^(licen[sc]e|copying|copyright|notice)([._-]|$)/i.test(entry.name))
    .map(entry => ({ file: path.join(directory, entry.name), label: entry.name }));
  if (value.license_file) {
    const file = path.resolve(directory, value.license_file);
    if (!files.some(entry => entry.file === file)) {
      files.push({ file, label: path.basename(file) });
    }
  }
  // tgrep-core inherits the repository's MIT license rather than repeating it
  // in the crate directory. Its Git revision is fixed by Cargo.lock.
  if (value.name === 'tgrep-core') {
    const file = path.resolve(directory, '../LICENSE');
    if (!files.some(entry => entry.file === file)) files.push({ file, label: 'LICENSE' });
  }
  if (files.length === 0) throw new Error(`No original license files found for ${key(value)}`);
  return files.sort((left, right) => compare(left.label, right.label));
}

const sorted = [...packages.values()].sort((left, right) => compare(key(left), key(right)));
let text = `CC Buddy embedded tgrep third-party notices

Generated by native/Scripts/generate-tgrep-notices.js from Cargo.lock.
Targets: aarch64-apple-darwin and x86_64-apple-darwin.
The upstream tgrep-core source is unmodified. CC Buddy's C ABI, private
checkpoint lifecycle, Unicode normalization, and file-catalog synchronization are
maintained separately in native/TgrepBridge and TgrepSearchIndex.swift.

The runtime list conservatively includes the complete normal-dependency graph
before link-time dead-code elimination, not a claim that every crate function
is present in the final dylib. Build-only and procedural-macro dependencies are
listed separately and their notices are retained for completeness. Original
license, copyright, and notice files follow verbatim, including alternative
licenses and additional BSD/Unicode terms. No private local paths are included.

Runtime dependencies (${runtime.size}):
${sorted.filter(value => runtime.has(key(value))).map(value => `  ${key(value)} — ${value.license}`).join('\n')}

Build-only and procedural-macro dependencies (${packages.size - runtime.size}):
${sorted.filter(value => !runtime.has(key(value))).map(value => `  ${key(value)} — ${value.license}`).join('\n')}
`;

for (const value of sorted) {
  text += `\n${'='.repeat(78)}\n${key(value)}\n`;
  text += `Role: ${runtime.has(key(value)) ? 'runtime dependency' : 'build-only / procedural macro'}\n`;
  text += `License expression: ${value.license}\nSource: ${value.source}\n`;
  for (const entry of licenseFiles(value)) {
    const license = fs.readFileSync(entry.file, 'utf8').replace(/\r\n/g, '\n').trimEnd();
    if (!license) throw new Error(`Empty license file for ${key(value)}: ${entry.label}`);
    text += `\n--- ${entry.label} ---\n${license}\n`;
  }
}

if (check) {
  if (fs.readFileSync(output, 'utf8') !== text) {
    throw new Error('Embedded tgrep notices differ from the locked dependency licenses; regenerate them.');
  }
  console.log(`Verified ${runtime.size} runtime and ${packages.size - runtime.size} build dependency notices.`);
} else {
  fs.writeFileSync(output, text);
  console.log(`Generated ${runtime.size} runtime and ${packages.size - runtime.size} build dependency notices.`);
}
