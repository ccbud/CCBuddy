#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import url from "node:url";

const argumentsSet = new Set(process.argv.slice(2));
for (const argument of argumentsSet) {
  if (argument !== "--check") throw new Error(`Unknown argument: ${argument}`);
}

const scriptDirectory = path.dirname(url.fileURLToPath(import.meta.url));
const nativeRoot = path.resolve(scriptDirectory, "..");
const helperRoot = path.join(nativeRoot, "GatewayHelper");
const overrideRoot = path.join(helperRoot, "license-overrides");
const outputPath = path.join(helperRoot, "THIRD-PARTY-NOTICES.txt");
const bundledOutputPath = path.join(
  nativeRoot,
  "Resources",
  "CCBuddyGateway-THIRD-PARTY-NOTICES.txt"
);
const targetTriple = "aarch64-apple-darwin";
const lockDigest = createHash("sha256")
  .update(fs.readFileSync(path.join(helperRoot, "Cargo.lock")))
  .digest("hex");

const metadata = JSON.parse(execFileSync(
  "cargo",
  [
    "metadata",
    "--format-version", "1",
    "--locked",
    "--filter-platform", targetTriple,
  ],
  {
    cwd: helperRoot,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  }
));

if (!metadata.resolve?.root) throw new Error("Cargo metadata did not identify the root package");
const activeTree = execFileSync(
  "cargo",
  [
    "tree",
    "--locked",
    "--target", targetTriple,
    "--edges", "normal,build",
    "--prefix", "none",
    "--format", "{p}",
  ],
  {
    cwd: helperRoot,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  }
);
const activePackageKeys = new Set(activeTree.trim().split("\n").map((line) => {
  const match = line.match(/^([^ ]+) v([^ ]+)(?: |$)/);
  if (!match) throw new Error(`Could not parse cargo tree package: ${line}`);
  return `${match[1]}\u0000${match[2]}`;
}));
const rootPackage = metadata.packages.find((item) => item.id === metadata.resolve.root);
if (!rootPackage) throw new Error("Cargo metadata is missing the root package");
activePackageKeys.delete(`${rootPackage.name}\u0000${rootPackage.version}`);

const compareText = (left, right) => left < right ? -1 : left > right ? 1 : 0;
const packages = metadata.packages
  .filter((item) => activePackageKeys.has(`${item.name}\u0000${item.version}`))
  .sort((left, right) => compareText(
    `${left.name}\u0000${left.version}\u0000${left.id}`,
    `${right.name}\u0000${right.version}\u0000${right.id}`
  ));
if (packages.length !== activePackageKeys.size) {
  throw new Error(
    `Cargo metadata matched ${packages.length} of ${activePackageKeys.size} active package versions`
  );
}

function normalizedText(filePath) {
  const value = fs.readFileSync(filePath, "utf8")
    .replaceAll("\r\n", "\n")
    .replace(/[ \t]+$/gm, "");
  if (value.includes("\u0000")) throw new Error(`License file is not text: ${filePath}`);
  return value.trimEnd();
}

function licenseFiles(item) {
  const packageRoot = path.dirname(item.manifest_path);
  const candidates = [];
  const pendingDirectories = [packageRoot];
  while (pendingDirectories.length > 0) {
    const directory = pendingDirectories.pop();
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const filePath = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        pendingDirectories.push(filePath);
      } else if (
        entry.isFile()
          && /^(?:licen[cs]e|unlicense|copying|notice|copyright|patents|third[-_ ]party)/i.test(entry.name)
      ) {
        candidates.push({
          label: path.relative(packageRoot, filePath).split(path.sep).join("/"),
          filePath,
        });
      }
    }
  }

  if (item.license_file) {
    const filePath = path.isAbsolute(item.license_file)
      ? item.license_file
      : path.join(packageRoot, item.license_file);
    candidates.push({ label: path.basename(filePath), filePath });
  }

  const overrideName = `${item.name}-${item.version}-LICENSE`;
  const overridePath = path.join(overrideRoot, overrideName);
  if (candidates.length === 0 && fs.existsSync(overridePath)) {
    candidates.push({
      label: `${overrideName} (upstream version-tag fallback)`,
      filePath: overridePath,
    });
  }

  const unique = new Map();
  for (const candidate of candidates) {
    const resolved = fs.realpathSync(candidate.filePath);
    if (!unique.has(resolved)) unique.set(resolved, candidate);
  }
  const result = [...unique.values()].sort((left, right) => compareText(left.label, right.label));
  if (result.length === 0) {
    throw new Error(`No packaged or reviewed fallback license text for ${item.name} ${item.version}`);
  }
  return result;
}

const lines = [
  "CC Buddy Gateway Helper — Third-Party Notices",
  "================================================",
  "",
  "Generated by native/Scripts/generate-gateway-third-party-notices.mjs from",
  "native/GatewayHelper/Cargo.lock. Do not edit this file by hand.",
  "",
  `Target: ${targetTriple}`,
  `Cargo.lock SHA-256: ${lockDigest}`,
  "Scope: non-development crates reachable through normal or build dependency edges.",
  `Crates: ${packages.length}`,
  "",
  "The CC Buddy project license and the separate cc-switch attribution are distributed in",
  "LICENSE and CCBuddyGateway-NOTICE.txt. The entries below reproduce the license and notice",
  "files packaged by each locked Rust crate. A reviewed upstream version-tag fallback is used",
  "only when crates.io omitted the referenced license file.",
  "",
];

for (const item of packages) {
  if (!item.license) throw new Error(`Package has no declared license expression: ${item.id}`);
  const source = item.repository ?? item.homepage
    ?? `https://crates.io/crates/${encodeURIComponent(item.name)}/${encodeURIComponent(item.version)}`;
  const files = licenseFiles(item);
  lines.push(
    "--------------------------------------------------------------------------------",
    `${item.name} ${item.version}`,
    `License expression: ${item.license}`,
    `Source: ${source}`,
    `Included notices: ${files.map((file) => file.label).join(", ")}`,
    "--------------------------------------------------------------------------------",
    ""
  );
  for (const file of files) {
    lines.push(
      `----- BEGIN ${file.label} -----`,
      normalizedText(file.filePath),
      `----- END ${file.label} -----`,
      ""
    );
  }
}

const generated = `${lines.join("\n").trimEnd()}\n`;
if (argumentsSet.has("--check")) {
  const existing = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : null;
  const bundled = fs.existsSync(bundledOutputPath)
    ? fs.readFileSync(bundledOutputPath, "utf8")
    : null;
  if (existing !== generated || bundled !== generated) {
    process.stderr.write(
      "Gateway third-party notices are stale; run "
        + "node native/Scripts/generate-gateway-third-party-notices.mjs\n"
    );
    process.exitCode = 1;
  } else {
    process.stdout.write(`Verified ${packages.length} locked gateway dependency notices\n`);
  }
} else {
  fs.writeFileSync(outputPath, generated);
  fs.writeFileSync(bundledOutputPath, generated);
  process.stdout.write(
    `Generated ${packages.length} gateway dependency notices at ${outputPath} and ${bundledOutputPath}\n`
  );
}
