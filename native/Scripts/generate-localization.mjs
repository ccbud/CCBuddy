#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import url from "node:url";

const scriptDirectory = path.dirname(url.fileURLToPath(import.meta.url));
const nativeRoot = path.resolve(scriptDirectory, "..");
const dictionaryRoot = path.resolve(nativeRoot, "../src/shared/i18n");
const outputRoot = path.join(nativeRoot, "Resources");
const overridePath = path.join(scriptDirectory, "native-localization-overrides.json");
const parts = ["app", "conv", "ops", "settings"];
const locales = {
  en: "en",
  ja: "ja",
  ko: "ko",
  "zh-Hans": "zh",
  "zh-Hant": "zh-TW",
};

function readDictionary(locale) {
  const result = {};
  for (const part of parts) {
    const file = path.join(dictionaryRoot, `${locale}-${part}.js`);
    const source = fs.readFileSync(file, "utf8");
    const match = source.match(/var part = (\{[\s\S]*?\n  \});/);
    if (!match) throw new Error(`Cannot parse ${file}`);
    // The checked-in dictionaries are JavaScript object literals (some retain trailing commas),
    // not strict JSON. They contain data-only string properties and are repository-owned input.
    const values = Function(`"use strict"; return (${match[1]});`)();
    Object.assign(result, values);
  }
  return result;
}

function withoutMarkup(value) {
  return value.replace(/<[^>]+>/g, "");
}

function escaped(value) {
  return value
    .replaceAll("\\", "\\\\")
    .replaceAll("\"", "\\\"")
    .replaceAll("\n", "\\n")
    .replaceAll("\r", "\\r");
}

const dictionaries = Object.fromEntries(
  [...new Set(Object.values(locales))].map((locale) => [locale, readDictionary(locale)])
);
const overrides = JSON.parse(fs.readFileSync(overridePath, "utf8"));
const sourceDictionary = dictionaries.zh;

function placeholders(value) {
  return [...value.matchAll(/\{([A-Za-z0-9_]+)\}/g)].map((match) => match[1]).sort();
}

for (const [source, values] of Object.entries(overrides)) {
  if (!values || typeof values !== "object" || Array.isArray(values)) {
    throw new Error(`Localization override must be an object: ${source}`);
  }
  const expectedPlaceholders = placeholders(source).join("\u0000");
  for (const lproj of Object.keys(locales)) {
    if (typeof values[lproj] !== "string" || values[lproj].length === 0) {
      throw new Error(`Localization override is missing ${lproj}: ${source}`);
    }
    if (placeholders(values[lproj]).join("\u0000") !== expectedPlaceholders) {
      throw new Error(`Localization placeholders differ for ${lproj}: ${source}`);
    }
  }
}

for (const [lproj, locale] of Object.entries(locales)) {
  const translations = new Map();
  const targetDictionary = dictionaries[locale];
  for (const [semanticKey, chineseSource] of Object.entries(sourceDictionary)) {
    const translated = targetDictionary[semanticKey] ?? chineseSource;
    const candidates = [
      [chineseSource, translated],
      [withoutMarkup(chineseSource), withoutMarkup(translated)],
    ];
    for (const [source, target] of candidates) {
      if (!source || translations.has(source)) continue;
      translations.set(source, target);
    }
  }

  for (const [source, values] of Object.entries(overrides)) {
    translations.set(source, values[lproj] ?? values[locale] ?? values["zh-Hans"] ?? source);
  }

  const directory = path.join(outputRoot, `${lproj}.lproj`);
  fs.mkdirSync(directory, { recursive: true });
  const header = [
    "/* Generated by Scripts/generate-localization.mjs. Do not edit by hand. */",
    "",
  ];
  const lines = [...translations.entries()]
    .sort(([left], [right]) => left.localeCompare(right, "zh-Hans"))
    .map(([source, target]) => `"${escaped(source)}" = "${escaped(target)}";`);
  fs.writeFileSync(path.join(directory, "Localizable.strings"), [...header, ...lines, ""].join("\n"));
}

console.log(`Generated ${Object.keys(locales).length} localization tables in ${outputRoot}`);
