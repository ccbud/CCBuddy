fn emit(app: &tauri::AppHandle, id: &str, item: &Value) {
    let _ = app.emit(EVENT, json!({ "id": id, "item": item }));
}

/// Persist + emit one normalized item. `delta` and `status` are emit-only (live state; stale
/// after a restart) — everything else is stamped with a per-session `seq` and appended to disk.
fn push_item(app: &tauri::AppHandle, state: &ChatState, id: &str, it: &Value) {
    let kind = it.get("kind").and_then(|v| v.as_str()).unwrap_or("");
    if kind == "delta" || kind == "status" {
        emit(app, id, it);
        return;
    }
    let mut stamped = it.clone();
    if let Some(obj) = stamped.as_object_mut() {
        obj.insert("seq".into(), json!(state.next_seq(id)));
    }
    append_item(id, &stamped);
    emit(app, id, &stamped);
}

async fn gateway_wire(gw: &std::sync::Arc<crate::gateway::GatewayState>) -> Option<GatewayWire> {
    let port = gw.current_port().await?;
    let cfg = crate::store::read_config();
    Some(GatewayWire {
        port,
        token: crate::claude::current_token(&cfg),
        codex_model: crate::codex_model(&cfg),
    })
}

struct TurnSpec {
    id: String,
    agent: String,
    cwd: String,
    prompt: String,
    permission: String,
    resume: Option<String>,
}

async fn run_turn(
    app: tauri::AppHandle,
    state: std::sync::Arc<ChatState>,
    gw: std::sync::Arc<crate::gateway::GatewayState>,
    spec: TurnSpec,
) {
    let id = spec.id.clone();
    let bin = match find_cli(&spec.agent) {
        Some(b) => b,
        None => {
            let it = item("error", json!({ "message": format!("{} CLI not found", spec.agent), "code": "cliMissing" }));
            push_item(&app, &state, &id, &it);
            finish(&app, &state, &id, "error");
            return;
        }
    };

    let wire = gateway_wire(&gw).await;
    let via_gateway = wire.is_some();
    let mut cmd = cli_command(&bin);
    if spec.agent == "claude" {
        cmd.args(claude_args(&spec.permission, spec.resume.as_deref()));
        cmd.current_dir(&spec.cwd);
        if let Some(w) = &wire {
            cmd.env("ANTHROPIC_BASE_URL", format!("http://127.0.0.1:{}", w.port));
            cmd.env("ANTHROPIC_AUTH_TOKEN", &w.token);
        }
    } else {
        cmd.args(codex_args(&spec.cwd, &spec.permission, spec.resume.as_deref(), wire.as_ref()));
        cmd.current_dir(&spec.cwd);
    }

    let (kill_tx, kill_rx) = tokio::sync::oneshot::channel::<()>();
    state.set_running(&id, kill_tx);
    push_item(&app, &state, &id, &item("status", json!({ "state": "running", "viaGateway": via_gateway })));

    let is_claude = spec.agent == "claude";
    let outcome = stream_child(cmd, spec.prompt.clone(), is_claude, spec.resume.clone(), kill_rx, |it| {
        if it.get("kind").and_then(|v| v.as_str()) == Some("meta") {
            if let Some(sid) = it.get("cliSessionId").and_then(|v| v.as_str()) {
                update_session(&id, json!({ "cliSessionId": sid }));
            }
        }
        push_item(&app, &state, &id, &it);
    })
    .await;
    state.clear_running(&id);

    let o = match outcome {
        Ok(o) => o,
        Err(e) => {
            push_item(&app, &state, &id, &item("error", json!({ "message": e })));
            finish(&app, &state, &id, "error");
            return;
        }
    };

    if o.stopped {
        push_item(&app, &state, &id, &item("result", json!({ "ok": false, "stopped": true })));
    } else if !o.parse.saw_result && !o.exit_ok {
        // Crashed before emitting a result event — surface the stderr tail.
        let msg = if o.stderr_tail.trim().is_empty() {
            format!("{} exited with {:?}", spec.agent, o.exit_code)
        } else {
            truncate(o.stderr_tail.trim(), 600)
        };
        push_item(&app, &state, &id, &item("error", json!({ "message": msg })));
        push_item(&app, &state, &id, &item("result", json!({ "ok": false, "error": msg })));
    } else if !o.parse.saw_result {
        push_item(&app, &state, &id, &item("result", json!({ "ok": true })));
    }

    // Session id can also arrive only late in the stream (e.g. only in the result record).
    if let Some(sid) = &o.parse.cli_session_id {
        update_session(&id, json!({ "cliSessionId": sid }));
    }
    let failed = o.parse.error.is_some() || (!o.parse.saw_result && !o.exit_ok);
    finish(&app, &state, &id, if !o.stopped && failed { "error" } else { "idle" });
}

struct StreamOutcome {
    parse: TurnParse,
    stopped: bool,
    exit_ok: bool,
    exit_code: Option<i32>,
    stderr_tail: String,
}

/// The whole child lifecycle: spawn the CLI, feed `prompt` on stdin, normalize each stdout line
/// into items for `on_item`, collect a rolling stderr tail, and stop early when `kill_rx` fires.
/// run_turn wraps this with session bookkeeping; tests drive it directly with mock CLIs.
async fn stream_child(
    mut cmd: tokio::process::Command,
    prompt: String,
    is_claude: bool,
    resume: Option<String>,
    mut kill_rx: tokio::sync::oneshot::Receiver<()>,
    mut on_item: impl FnMut(Value),
) -> Result<StreamOutcome, String> {
    cmd.stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .kill_on_drop(true);
    #[cfg(windows)]
    {
        // CREATE_NO_WINDOW — no flashing console on Windows.
        use std::os::windows::process::CommandExt as _;
        cmd.creation_flags(0x0800_0000);
    }

    let mut child = cmd.spawn().map_err(|e| format!("spawn failed: {}", e))?;

    // Prompt goes through stdin (claude reads the -p prompt from stdin; codex got the "-" arg).
    if let Some(mut stdin) = child.stdin.take() {
        use tokio::io::AsyncWriteExt;
        let _ = stdin.write_all(prompt.as_bytes()).await;
        let _ = stdin.shutdown().await;
        drop(stdin);
    }

    let stdout = child.stdout.take();
    let stderr = child.stderr.take();

    // stderr → rolling tail, surfaced only when the run dies without a result event.
    let err_tail = std::sync::Arc::new(Mutex::new(String::new()));
    let err_tail2 = err_tail.clone();
    let stderr_task = tokio::spawn(async move {
        if let Some(se) = stderr {
            use tokio::io::AsyncBufReadExt;
            let mut lines = tokio::io::BufReader::new(se).lines();
            while let Ok(Some(l)) = lines.next_line().await {
                if let Ok(mut t) = err_tail2.lock() {
                    t.push_str(&l);
                    t.push('\n');
                    if t.len() > 4000 {
                        let cut = t.len() - 4000;
                        *t = t[cut..].to_string();
                    }
                }
            }
        }
    });

    let mut st = TurnParse::default();
    if resume.is_some() {
        st.cli_session_id = resume;
    }
    let mut stopped = false;

    if let Some(so) = stdout {
        use tokio::io::AsyncBufReadExt;
        let mut lines = tokio::io::BufReader::new(so).lines();
        loop {
            tokio::select! {
                _ = &mut kill_rx => {
                    stopped = true;
                    let _ = child.start_kill();
                    break;
                }
                line = lines.next_line() => {
                    match line {
                        Ok(Some(l)) => {
                            let items = if is_claude { parse_claude_line(&l, &mut st) } else { parse_codex_line(&l, &mut st) };
                            for it in items {
                                on_item(it);
                            }
                        }
                        _ => break,
                    }
                }
            }
        }
    }

    let exit = child.wait().await;
    let _ = stderr_task.await;

    Ok(StreamOutcome {
        stopped,
        exit_ok: exit.as_ref().map(|s| s.success()).unwrap_or(false),
        exit_code: exit.ok().and_then(|s| s.code()),
        stderr_tail: err_tail.lock().map(|t| t.clone()).unwrap_or_default(),
        parse: st,
    })
}

fn finish(app: &tauri::AppHandle, state: &ChatState, id: &str, state_str: &str) {
    state.clear_running(id);
    update_session(id, json!({ "status": state_str }));
    emit(app, id, &item("status", json!({ "state": state_str })));
}

