            assert_eq!(out.parse.cli_session_id.as_deref(), Some("th-1"));
            let kinds: Vec<&str> = got.iter().map(|i| i["kind"].as_str().unwrap()).collect();
            assert_eq!(kinds, vec!["meta", "assistant", "result"]);
