#[tauri::command]
pub fn chat_list(state: tauri::State<'_, std::sync::Arc<ChatState>>) -> Value {
    let mut list = read_registry();
    for s in list.iter_mut() {
        let id = s.get("id").and_then(|v| v.as_str()).unwrap_or("").to_string();
        let running = state.is_running(&id);
        if let Some(obj) = s.as_object_mut() {
            // A stale "running" from a previous app run means the process is gone.
            if !running && obj.get("status").and_then(|v| v.as_str()) == Some("running") {
                obj.insert("status".into(), json!("idle"));
            }
            obj.insert("running".into(), json!(running));
        }
    }
    list.sort_by(|a, b| {
        let am = a.get("updatedMs").and_then(|v| v.as_i64()).unwrap_or(0);
        let bm = b.get("updatedMs").and_then(|v| v.as_i64()).unwrap_or(0);
        bm.cmp(&am)
    });
    Value::Array(list)
}

