static SESSION_SEQ: AtomicU64 = AtomicU64::new(0);

fn new_id() -> String {
    format!("{}-{}", now_ms(), SESSION_SEQ.fetch_add(1, Ordering::Relaxed))
}

fn expand_tilde(p: &str) -> String {
    if let Some(rest) = p.strip_prefix("~/") {
        if let Ok(home) = std::env::var("HOME") {
            return format!("{}/{}", home, rest);
        }
    }
    if p == "~" {
        if let Ok(home) = std::env::var("HOME") {
            return home;
        }
    }
    p.to_string()
}

#[tauri::command]
pub async fn chat_start(
    app: tauri::AppHandle,
    state: tauri::State<'_, std::sync::Arc<ChatState>>,
    gw: tauri::State<'_, std::sync::Arc<crate::gateway::GatewayState>>,
    agent: String,
    cwd: String,
    prompt: String,
    permission: Option<String>,
) -> Result<Value, String> {
    let agent = if agent == "codex" { "codex" } else { "claude" }.to_string();
    let cwd = expand_tilde(cwd.trim());
    if !Path::new(&cwd).is_dir() {
        return Ok(json!({ "ok": false, "reason": "badDir" }));
    }
    let prompt_trim = prompt.trim().to_string();
    if prompt_trim.is_empty() {
        return Ok(json!({ "ok": false, "reason": "empty" }));
    }
    let permission = permission.unwrap_or_else(|| "edits".to_string());
    let id = new_id();
    let title = truncate(prompt_trim.replace('\n', " ").trim(), 64);
    update_session(
        &id,
        json!({ "agent": agent, "cwd": cwd, "title": title, "permission": permission, "status": "running" }),
    );
    push_item(&app, &state, &id, &item("user", json!({ "text": prompt_trim })));

    let spec = TurnSpec { id: id.clone(), agent, cwd, prompt: prompt_trim, permission, resume: None };
    let st = state.inner().clone();
    let gws = gw.inner().clone();
    tauri::async_runtime::spawn(run_turn(app, st, gws, spec));
    Ok(json!({ "ok": true, "id": id }))
}

#[tauri::command]
pub async fn chat_send(
    app: tauri::AppHandle,
    state: tauri::State<'_, std::sync::Arc<ChatState>>,
    gw: tauri::State<'_, std::sync::Arc<crate::gateway::GatewayState>>,
    id: String,
    prompt: String,
) -> Result<Value, String> {
    let sess = match get_session(&id) {
        Some(s) => s,
        None => return Ok(json!({ "ok": false, "reason": "notFound" })),
    };
    if state.is_running(&id) {
        return Ok(json!({ "ok": false, "reason": "busy" }));
    }
    let prompt_trim = prompt.trim().to_string();
    if prompt_trim.is_empty() {
        return Ok(json!({ "ok": false, "reason": "empty" }));
    }
    let agent = sess.get("agent").and_then(|v| v.as_str()).unwrap_or("claude").to_string();
    let cwd = sess.get("cwd").and_then(|v| v.as_str()).unwrap_or(".").to_string();
    let permission = sess.get("permission").and_then(|v| v.as_str()).unwrap_or("edits").to_string();
    let resume = sess.get("cliSessionId").and_then(|v| v.as_str()).map(|s| s.to_string());

    update_session(&id, json!({ "status": "running" }));
    push_item(&app, &state, &id, &item("user", json!({ "text": prompt_trim })));

    let spec = TurnSpec { id: id.clone(), agent, cwd, prompt: prompt_trim, permission, resume };
    let st = state.inner().clone();
    let gws = gw.inner().clone();
    tauri::async_runtime::spawn(run_turn(app, st, gws, spec));
    Ok(json!({ "ok": true, "id": id }))
}

