// New Session chat — run a coding CLI (Claude Code / Codex) as a child process per turn and
// stream its JSON event output into the renderer as normalized chat items (the cdesktop model,
// pared down to one-shot `-p` / `exec` turns resumed via the CLI's own session id).
//
// Wiring: when the local gateway is running, the spawned CLI is pointed at it per-process —
// Claude via ANTHROPIC_BASE_URL/ANTHROPIC_AUTH_TOKEN env, Codex via `-c` config overrides —
// so chats route through the active provider without touching the user's own CLI config.
// The CLIs still write their native transcripts (~/.claude/projects, ~/.codex/sessions), so
// finished chats also show up in the regular Sessions view.
//
// State: a registry (~/.ccbud/chat/sessions.json) + one JSONL of normalized items per session
// (~/.ccbud/chat/<id>.jsonl). Live turns additionally emit `chat:event` {id, item}; text deltas
// are emit-only (never persisted) — the finalized message follows as its own item.

use serde_json::{json, Map, Value};
use std::collections::HashMap;
use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Mutex;
use tauri::Emitter;

const EVENT: &str = "chat:event";

fn now_ms() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_millis() as i64)
        .unwrap_or(0)
}

// ---------- state ----------

#[derive(Default)]
pub struct ChatState {
    // session id → sender that aborts the running turn's child process.
    running: Mutex<HashMap<String, tokio::sync::oneshot::Sender<()>>>,
    // session id → next item sequence number. Persisted items carry `seq` so the renderer can
    // drop live events it already replayed from disk (chat_get vs chat:event race on open).
    seqs: Mutex<HashMap<String, u64>>,
}

impl ChatState {
    fn is_running(&self, id: &str) -> bool {
        self.running.lock().map(|m| m.contains_key(id)).unwrap_or(false)
    }
    fn take_kill(&self, id: &str) -> Option<tokio::sync::oneshot::Sender<()>> {
        self.running.lock().ok().and_then(|mut m| m.remove(id))
    }
    fn set_running(&self, id: &str, tx: tokio::sync::oneshot::Sender<()>) {
        if let Ok(mut m) = self.running.lock() {
            m.insert(id.to_string(), tx);
        }
    }
    fn clear_running(&self, id: &str) {
        if let Ok(mut m) = self.running.lock() {
            m.remove(id);
        }
    }
    pub fn kill_all(&self) {
        if let Ok(mut m) = self.running.lock() {
            for (_, tx) in m.drain() {
                let _ = tx.send(());
            }
        }
    }
    /// Next persisted-item sequence for a session, seeded from the on-disk item count.
    fn next_seq(&self, id: &str) -> u64 {
        let mut m = match self.seqs.lock() {
            Ok(m) => m,
            Err(_) => return 0,
        };
        let n = m.entry(id.to_string()).or_insert_with(|| read_items(id).len() as u64);
        let v = *n;
        *n += 1;
        v
    }
    fn drop_seq(&self, id: &str) {
        if let Ok(mut m) = self.seqs.lock() {
            m.remove(id);
        }
    }
}

// ---------- persistence ----------

fn chat_dir() -> PathBuf {
    crate::store::ccbud_home().join("chat")
}

fn items_path(dir: &Path, id: &str) -> PathBuf {
    // ids are generated by us (digits + dashes), safe as file names.
    dir.join(format!("{}.jsonl", id))
}

fn read_registry_in(dir: &Path) -> Vec<Value> {
    std::fs::read_to_string(dir.join("sessions.json"))
        .ok()
        .and_then(|s| serde_json::from_str::<Value>(&s).ok())
        .and_then(|v| v.as_array().cloned())
        .unwrap_or_default()
}

fn write_registry_in(dir: &Path, list: &[Value]) {
    let _ = std::fs::create_dir_all(dir);
    let path = dir.join("sessions.json");
    let tmp = path.with_extension("json.tmp");
    if std::fs::write(&tmp, serde_json::to_vec_pretty(&Value::Array(list.to_vec())).unwrap_or_default()).is_ok() {
        let _ = std::fs::rename(&tmp, path);
    }
}

fn read_registry() -> Vec<Value> {
    read_registry_in(&chat_dir())
}

fn write_registry(list: &[Value]) {
    write_registry_in(&chat_dir(), list)
}

/// Merge `patch` into the registry entry `id` (creating it if new) and bump updatedMs.
fn update_session_in(dir: &Path, id: &str, patch: Value) {
    let mut list = read_registry_in(dir);
    let mut found = false;
    for s in list.iter_mut() {
        if s.get("id").and_then(|v| v.as_str()) == Some(id) {
            if let (Some(obj), Some(p)) = (s.as_object_mut(), patch.as_object()) {
                for (k, v) in p {
                    obj.insert(k.clone(), v.clone());
                }
                obj.insert("updatedMs".into(), json!(now_ms()));
            }
            found = true;
            break;
        }
    }
    if !found {
        let mut obj = Map::new();
        obj.insert("id".into(), json!(id));
        obj.insert("createdMs".into(), json!(now_ms()));
        obj.insert("updatedMs".into(), json!(now_ms()));
        if let Some(p) = patch.as_object() {
            for (k, v) in p {
                obj.insert(k.clone(), v.clone());
            }
        }
        list.push(Value::Object(obj));
    }
    write_registry_in(dir, &list);
}

fn update_session(id: &str, patch: Value) {
    update_session_in(&chat_dir(), id, patch)
}

fn get_session_in(dir: &Path, id: &str) -> Option<Value> {
    read_registry_in(dir).into_iter().find(|s| s.get("id").and_then(|v| v.as_str()) == Some(id))
}

fn get_session(id: &str) -> Option<Value> {
    get_session_in(&chat_dir(), id)
}

fn append_item_in(dir: &Path, id: &str, item: &Value) {
    let _ = std::fs::create_dir_all(dir);
    if let Ok(mut f) = std::fs::OpenOptions::new().create(true).append(true).open(items_path(dir, id)) {
        let mut line = serde_json::to_vec(item).unwrap_or_default();
        line.push(b'\n');
        let _ = f.write_all(&line);
    }
}

fn append_item(id: &str, item: &Value) {
    append_item_in(&chat_dir(), id, item)
}

fn read_items_in(dir: &Path, id: &str) -> Vec<Value> {
    std::fs::read_to_string(items_path(dir, id))
        .map(|s| s.lines().filter_map(|l| serde_json::from_str::<Value>(l).ok()).collect())
        .unwrap_or_default()
}

fn read_items(id: &str) -> Vec<Value> {
    read_items_in(&chat_dir(), id)
}

// ---------- CLI resolution ----------

fn candidate_dirs() -> Vec<PathBuf> {
    let home = std::env::var("HOME").map(PathBuf::from).unwrap_or_else(|_| PathBuf::from("."));
    vec![
        home.join(".local/bin"),
        home.join(".claude/local"),
        home.join(".bun/bin"),
        home.join(".cargo/bin"),
        home.join(".volta/bin"),
        home.join(".deno/bin"),
        home.join("n/bin"),
        home.join(".npm-global/bin"),
        PathBuf::from("/opt/homebrew/bin"),
        PathBuf::from("/usr/local/bin"),
        PathBuf::from("/usr/bin"),
    ]
}

#[cfg(windows)]
fn exe_names(name: &str) -> Vec<String> {
    vec![format!("{}.exe", name), format!("{}.cmd", name), name.to_string()]
}
#[cfg(not(windows))]
fn exe_names(name: &str) -> Vec<String> {
    vec![name.to_string()]
}

fn cli_cache() -> &'static Mutex<HashMap<String, Option<PathBuf>>> {
    static CACHE: std::sync::OnceLock<Mutex<HashMap<String, Option<PathBuf>>>> = std::sync::OnceLock::new();
    CACHE.get_or_init(|| Mutex::new(HashMap::new()))
}

/// Resolve a CLI by name: PATH first, then common install dirs, then (unix) a login-shell
/// `command -v` — GUI apps on macOS don't inherit the user's shell PATH. Result is memoized;
/// a miss is retried on every call so installing the CLI mid-run is picked up.
pub(crate) fn find_cli(name: &str) -> Option<PathBuf> {
    if let Ok(cache) = cli_cache().lock() {
        if let Some(Some(p)) = cache.get(name) {
            if p.is_file() {
                return Some(p.clone());
            }
        }
    }
    let found = find_cli_uncached(name);
    if let Ok(mut cache) = cli_cache().lock() {
        cache.insert(name.to_string(), found.clone());
    }
    found
}

fn find_cli_uncached(name: &str) -> Option<PathBuf> {
    let names = exe_names(name);
    if let Some(paths) = std::env::var_os("PATH") {
        for dir in std::env::split_paths(&paths) {
            for n in &names {
                let p = dir.join(n);
                if p.is_file() {
                    return Some(p);
                }
            }
        }
    }
    for dir in candidate_dirs() {
        for n in &names {
            let p = dir.join(n);
            if p.is_file() {
                return Some(p);
            }
        }
    }
    #[cfg(unix)]
    {
        let shell = std::env::var("SHELL").unwrap_or_else(|_| "/bin/sh".into());
        if let Ok(out) = std::process::Command::new(&shell)
            .args(["-l", "-c", &format!("command -v {}", name)])
            .output()
        {
            if out.status.success() {
                let p = String::from_utf8_lossy(&out.stdout).trim().to_string();
                if !p.is_empty() {
                    let pb = PathBuf::from(p);
                    if pb.is_file() {
                        return Some(pb);
                    }
                }
            }
        }
    }
    None
}

/// Build a Command for a resolved CLI path. Windows `.cmd` shims need `cmd /C`.
fn cli_command(path: &Path) -> tokio::process::Command {
    #[cfg(windows)]
    {
        if path.extension().map(|e| e.eq_ignore_ascii_case("cmd") || e.eq_ignore_ascii_case("bat")).unwrap_or(false) {
            let mut c = tokio::process::Command::new("cmd");
            c.arg("/C").arg(path);
            return c;
        }
    }
    tokio::process::Command::new(path)
}

// ---------- args / env ----------

struct GatewayWire {
    port: u16,
    token: String,
    codex_model: String,
}

fn claude_args(permission: &str, resume: Option<&str>) -> Vec<String> {
    let mode = match permission {
        "plan" => "plan",
        "full" => "bypassPermissions",
        _ => "acceptEdits",
    };
    let mut args = vec![
        "-p".to_string(),
        "--output-format".to_string(),
        "stream-json".to_string(),
        "--verbose".to_string(),
        "--include-partial-messages".to_string(),
        "--permission-mode".to_string(),
        mode.to_string(),
    ];
    if let Some(sid) = resume {
        args.push("--resume".to_string());
        args.push(sid.to_string());
    }
    args
}

fn codex_args(cwd: &str, permission: &str, resume: Option<&str>, gw: Option<&GatewayWire>) -> Vec<String> {
    // Flag order matters: exec-level flags go BEFORE the `resume` subcommand (clap parent flags
    // are only valid after a subcommand when declared global; before works either way).
    let mut args = vec!["exec".to_string()];
    args.push("--json".to_string());
    args.push("--skip-git-repo-check".to_string());
    args.push("-C".to_string());
    args.push(cwd.to_string());
    match permission {
        "plan" => {
            args.push("--sandbox".to_string());
            args.push("read-only".to_string());
        }
        "full" => args.push("--dangerously-bypass-approvals-and-sandbox".to_string()),
        _ => {
            args.push("--sandbox".to_string());
            args.push("workspace-write".to_string());
        }
    }
    if let Some(gw) = gw {
        // Same provider block codexconnect writes to config.toml, as per-process overrides.
        let kv = [
            ("model_provider".to_string(), "\"ccbud\"".to_string()),
            ("model".to_string(), format!("\"{}\"", gw.codex_model)),
            ("model_providers.ccbud.name".to_string(), "\"CC Buddy\"".to_string()),
            (
                "model_providers.ccbud.base_url".to_string(),
                format!("\"http://127.0.0.1:{}/v1\"", gw.port),
            ),
            ("model_providers.ccbud.wire_api".to_string(), "\"responses\"".to_string()),
            ("model_providers.ccbud.requires_openai_auth".to_string(), "false".to_string()),
            (
                "model_providers.ccbud.experimental_bearer_token".to_string(),
                format!("\"{}\"", gw.token),
            ),
        ];
        for (k, v) in kv {
            args.push("-c".to_string());
            args.push(format!("{}={}", k, v));
        }
    }
    if let Some(sid) = resume {
        args.push("resume".to_string());
        args.push(sid.to_string());
    }
    // Prompt is piped through stdin.
    args.push("-".to_string());
    args
}

// ---------- normalized items ----------

fn item(kind: &str, fields: Value) -> Value {
    let mut obj = Map::new();
    obj.insert("kind".into(), json!(kind));
    obj.insert("ts".into(), json!(now_ms()));
    if let Some(f) = fields.as_object() {
        for (k, v) in f {
            obj.insert(k.clone(), v.clone());
        }
    }
    Value::Object(obj)
}

fn truncate(s: &str, max: usize) -> String {
    if s.chars().count() <= max {
        return s.to_string();
    }
    let cut: String = s.chars().take(max).collect();
    format!("{}…", cut)
}

/// One-line human summary of a Claude tool_use input, keyed by tool name.
pub(crate) fn tool_detail(name: &str, input: &Value) -> String {
    let s = |k: &str| input.get(k).and_then(|v| v.as_str()).unwrap_or("").to_string();
    let d = match name {
        "Bash" => s("command"),
        "Read" | "Write" | "Edit" | "NotebookEdit" => s("file_path"),
        "Glob" | "Grep" => {
            let p = s("pattern");
            let path = s("path");
            if path.is_empty() { p } else { format!("{} · {}", p, path) }
        }
        "WebFetch" => s("url"),
        "WebSearch" => s("query"),
        "Task" => {
            let d = s("description");
            if d.is_empty() { s("prompt") } else { d }
        }
        "TodoWrite" => {
            let n = input.get("todos").and_then(|v| v.as_array()).map(|a| a.len()).unwrap_or(0);
            format!("{} todos", n)
        }
        _ => String::new(),
    };
    let d = if d.is_empty() {
        serde_json::to_string(input).unwrap_or_default()
    } else {
        d
    };
    truncate(d.replace('\n', " ").trim(), 220)
}

fn text_of(content: &Value) -> String {
    match content {
        Value::String(s) => s.clone(),
        Value::Array(arr) => arr
            .iter()
            .filter_map(|b| {
                if b.get("type").and_then(|t| t.as_str()) == Some("text") {
                    b.get("text").and_then(|t| t.as_str()).map(|s| s.to_string())
                } else {
                    None
                }
            })
            .collect::<Vec<_>>()
            .join("\n"),
        _ => String::new(),
    }
}

/// Per-turn parser state shared across stdout lines.
#[derive(Default)]
pub(crate) struct TurnParse {
    pub cli_session_id: Option<String>,
    pub saw_result: bool,
    pub error: Option<String>,
}

/// Normalize one line of `claude -p --output-format stream-json` output.
pub(crate) fn parse_claude_line(line: &str, st: &mut TurnParse) -> Vec<Value> {
    let rec: Value = match serde_json::from_str(line) {
        Ok(v) => v,
        Err(_) => return vec![],
    };
    if let Some(sid) = rec.get("session_id").and_then(|v| v.as_str()) {
        if !sid.is_empty() {
            st.cli_session_id = Some(sid.to_string());
        }
    }
    let t = rec.get("type").and_then(|v| v.as_str()).unwrap_or("");
    let mut out = vec![];
    match t {
        "system" => {
            if rec.get("subtype").and_then(|v| v.as_str()) == Some("init") {
                out.push(item(
                    "meta",
                    json!({
                        "model": rec.get("model").cloned().unwrap_or(Value::Null),
                        "cliSessionId": rec.get("session_id").cloned().unwrap_or(Value::Null),
                    }),
                ));
            }
        }
        "stream_event" => {
            // Partial text/thinking deltas for live typing; emit-only (never persisted).
            let ev = rec.get("event").cloned().unwrap_or(Value::Null);
            if ev.get("type").and_then(|v| v.as_str()) == Some("content_block_delta") {
                if let Some(d) = ev.get("delta") {
                    match d.get("type").and_then(|v| v.as_str()).unwrap_or("") {
                        "text_delta" => {
                            if let Some(txt) = d.get("text").and_then(|v| v.as_str()) {
                                out.push(item("delta", json!({ "text": txt })));
                            }
                        }
                        "thinking_delta" => {
                            if let Some(txt) = d.get("thinking").and_then(|v| v.as_str()) {
                                out.push(item("delta", json!({ "text": txt, "think": true })));
                            }
                        }
                        _ => {}
                    }
                }
            }
        }
        "assistant" => {
            // Sub-agent (Task) traffic replays with parent_tool_use_id set — the parent tool row
            // already represents it, so keep the main thread clean.
            if rec.get("parent_tool_use_id").and_then(|v| v.as_str()).is_some() {
                return out;
            }
            let blocks = rec
                .get("message")
                .and_then(|m| m.get("content"))
                .and_then(|c| c.as_array())
                .cloned()
                .unwrap_or_default();
            for b in blocks {
                match b.get("type").and_then(|v| v.as_str()).unwrap_or("") {
                    "text" => {
                        let txt = b.get("text").and_then(|v| v.as_str()).unwrap_or("");
                        if !txt.trim().is_empty() {
                            out.push(item("assistant", json!({ "text": txt })));
                        }
                    }
                    "thinking" => {
                        let txt = b.get("thinking").and_then(|v| v.as_str()).unwrap_or("");
                        if !txt.trim().is_empty() {
                            out.push(item("thinking", json!({ "text": txt })));
                        }
                    }
                    "tool_use" => {
                        let name = b.get("name").and_then(|v| v.as_str()).unwrap_or("tool");
                        let input = b.get("input").cloned().unwrap_or(json!({}));
                        out.push(item(
                            "tool",
                            json!({
                                "toolId": b.get("id").cloned().unwrap_or(Value::Null),
                                "name": name,
                                "detail": tool_detail(name, &input),
                            }),
                        ));
                    }
                    _ => {}
                }
            }
        }
        "user" => {
            if rec.get("parent_tool_use_id").and_then(|v| v.as_str()).is_some() {
                return out;
            }
            let blocks = rec
                .get("message")
                .and_then(|m| m.get("content"))
                .and_then(|c| c.as_array())
                .cloned()
                .unwrap_or_default();
            for b in blocks {
                if b.get("type").and_then(|v| v.as_str()) == Some("tool_result") {
                    let is_err = b.get("is_error").and_then(|v| v.as_bool()).unwrap_or(false);
                    let preview = truncate(text_of(&b.get("content").cloned().unwrap_or(Value::Null)).trim(), 400);
                    out.push(item(
                        "tool_result",
                        json!({
                            "toolId": b.get("tool_use_id").cloned().unwrap_or(Value::Null),
                            "ok": !is_err,
                            "detail": preview,
                        }),
                    ));
                }
            }
        }
        "result" => {
            st.saw_result = true;
            let is_err = rec.get("is_error").and_then(|v| v.as_bool()).unwrap_or(false);
            if is_err {
                st.error = Some(
                    rec.get("result")
                        .and_then(|v| v.as_str())
                        .unwrap_or("run failed")
                        .to_string(),
                );
            }
            out.push(item(
                "result",
                json!({
                    "ok": !is_err,
                    "durationMs": rec.get("duration_ms").cloned().unwrap_or(Value::Null),
                    "costUsd": rec.get("total_cost_usd").cloned().unwrap_or(Value::Null),
                    "usage": rec.get("usage").cloned().unwrap_or(Value::Null),
                    "error": if is_err { rec.get("result").cloned().unwrap_or(Value::Null) } else { Value::Null },
                }),
            ));
        }
        _ => {}
    }
    out
}

/// Normalize one line of `codex exec --json` output. Handles both the current thread/item
/// event stream and the older `{"msg":{...}}` protocol shape.
pub(crate) fn parse_codex_line(line: &str, st: &mut TurnParse) -> Vec<Value> {
    let rec: Value = match serde_json::from_str(line) {
        Ok(v) => v,
        Err(_) => return vec![],
    };
    let mut out = vec![];

    // Older codex: {"id":"...","msg":{"type":"agent_message",...}}
    if let Some(msg) = rec.get("msg") {
        let mt = msg.get("type").and_then(|v| v.as_str()).unwrap_or("");
        match mt {
            "session_configured" => {
                if let Some(sid) = msg.get("session_id").and_then(|v| v.as_str()) {
                    st.cli_session_id = Some(sid.to_string());
                    out.push(item("meta", json!({ "cliSessionId": sid, "model": msg.get("model").cloned().unwrap_or(Value::Null) })));
                }
            }
            "agent_message" => {
                if let Some(txt) = msg.get("message").and_then(|v| v.as_str()) {
                    out.push(item("assistant", json!({ "text": txt })));
                }
            }
            "agent_message_delta" => {
                if let Some(txt) = msg.get("delta").and_then(|v| v.as_str()) {
                    out.push(item("delta", json!({ "text": txt })));
                }
            }
            "agent_reasoning" => {
                if let Some(txt) = msg.get("text").and_then(|v| v.as_str()) {
                    out.push(item("thinking", json!({ "text": txt })));
                }
            }
            "exec_command_begin" => {
                let cmd = msg
                    .get("command")
                    .and_then(|v| v.as_array())
                    .map(|a| a.iter().filter_map(|x| x.as_str()).collect::<Vec<_>>().join(" "))
                    .unwrap_or_default();
                out.push(item(
                    "tool",
                    json!({ "toolId": msg.get("call_id").cloned().unwrap_or(Value::Null), "name": "Shell", "detail": truncate(&cmd, 220) }),
                ));
            }
            "exec_command_end" => {
                let code = msg.get("exit_code").and_then(|v| v.as_i64()).unwrap_or(0);
                out.push(item(
                    "tool_result",
                    json!({ "toolId": msg.get("call_id").cloned().unwrap_or(Value::Null), "ok": code == 0, "detail": "" }),
                ));
            }
            "task_complete" => {
                st.saw_result = true;
                out.push(item("result", json!({ "ok": true })));
            }
            "error" => {
                let m = msg.get("message").and_then(|v| v.as_str()).unwrap_or("error");
                st.error = Some(m.to_string());
                out.push(item("error", json!({ "message": m })));
            }
            _ => {}
        }
        return out;
    }

    let t = rec.get("type").and_then(|v| v.as_str()).unwrap_or("");
    match t {
        "thread.started" => {
            if let Some(sid) = rec.get("thread_id").and_then(|v| v.as_str()) {
                st.cli_session_id = Some(sid.to_string());
                out.push(item("meta", json!({ "cliSessionId": sid })));
            }
        }
        "item.started" | "item.updated" | "item.completed" => {
            let it = rec.get("item").cloned().unwrap_or(json!({}));
            let details = it.get("details").cloned().unwrap_or(Value::Null);
            let field = |k: &str| -> Value {
                it.get(k)
                    .cloned()
                    .or_else(|| details.get(k).cloned())
                    .unwrap_or(Value::Null)
            };
            let kind = it
                .get("item_type")
                .or_else(|| it.get("type"))
                .or_else(|| details.get("type"))
                .and_then(|v| v.as_str())
                .unwrap_or("");
            let done = t == "item.completed";
            match kind {
                "assistant_message" | "agent_message" => {
                    if done {
                        if let Some(txt) = field("text").as_str() {
                            if !txt.trim().is_empty() {
                                out.push(item("assistant", json!({ "text": txt })));
                            }
                        }
                    }
                }
                "reasoning" => {
                    if done {
                        if let Some(txt) = field("text").as_str() {
                            if !txt.trim().is_empty() {
                                out.push(item("thinking", json!({ "text": txt })));
                            }
                        }
                    }
                }
                "command_execution" => {
                    let id = it.get("id").cloned().unwrap_or(Value::Null);
                    if t == "item.started" {
                        let cmd = field("command").as_str().unwrap_or("").to_string();
                        out.push(item("tool", json!({ "toolId": id, "name": "Shell", "detail": truncate(&cmd, 220) })));
                    } else if done {
                        let code = field("exit_code").as_i64();
                        let status = field("status").as_str().unwrap_or("").to_string();
                        let ok = code.map(|c| c == 0).unwrap_or(status != "failed");
                        let tail = field("aggregated_output").as_str().unwrap_or("").to_string();
                        let tail = tail.lines().rev().take(6).collect::<Vec<_>>().into_iter().rev().collect::<Vec<_>>().join("\n");
                        out.push(item("tool_result", json!({ "toolId": id, "ok": ok, "detail": truncate(tail.trim(), 400) })));
                    }
                }
                "file_change" => {
                    if done {
                        let paths = field("changes")
                            .as_array()
                            .map(|a| {
                                a.iter()
                                    .filter_map(|c| c.get("path").and_then(|p| p.as_str()))
                                    .collect::<Vec<_>>()
                                    .join(", ")
                            })
                            .unwrap_or_default();
                        out.push(item("tool", json!({ "toolId": it.get("id").cloned().unwrap_or(Value::Null), "name": "Edit", "detail": truncate(&paths, 220), "done": true })));
                    }
                }
                "mcp_tool_call" => {
                    if done {
                        let name = format!(
                            "{}.{}",
                            field("server").as_str().unwrap_or("mcp"),
                            field("tool").as_str().unwrap_or("call")
                        );
                        out.push(item("tool", json!({ "toolId": it.get("id").cloned().unwrap_or(Value::Null), "name": name, "detail": "", "done": true })));
                    }
                }
                "web_search" => {
                    if done {
                        let q = field("query").as_str().unwrap_or("").to_string();
                        out.push(item("tool", json!({ "toolId": it.get("id").cloned().unwrap_or(Value::Null), "name": "WebSearch", "detail": truncate(&q, 220), "done": true })));
                    }
                }
                "todo_list" => {
                    if done {
                        let n = field("items").as_array().map(|a| a.len()).unwrap_or(0);
                        out.push(item("tool", json!({ "toolId": it.get("id").cloned().unwrap_or(Value::Null), "name": "Plan", "detail": format!("{} steps", n), "done": true })));
                    }
                }
                "error" => {
                    let m = field("message").as_str().unwrap_or("error").to_string();
                    st.error = Some(m.clone());
                    out.push(item("error", json!({ "message": m })));
                }
                _ => {}
            }
        }
        "turn.completed" => {
            st.saw_result = true;
            out.push(item(
                "result",
                json!({ "ok": true, "usage": rec.get("usage").cloned().unwrap_or(Value::Null) }),
            ));
        }
        "turn.failed" => {
            st.saw_result = true;
            let m = rec
                .get("error")
                .and_then(|e| e.get("message"))
                .and_then(|v| v.as_str())
                .unwrap_or("turn failed")
                .to_string();
            st.error = Some(m.clone());
            out.push(item("result", json!({ "ok": false, "error": m })));
        }
        "error" => {
            let m = rec.get("message").and_then(|v| v.as_str()).unwrap_or("error").to_string();
            st.error = Some(m.clone());
            out.push(item("error", json!({ "message": m })));
        }
        _ => {}
    }
    out
}

